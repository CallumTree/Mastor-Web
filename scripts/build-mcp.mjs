/**
 * Bundles the Claude connector (server/mcp/) into api/mcp.js — one self-contained file Vercel can run,
 * carrying the app's own calculations from src/lib. Run after changing server/mcp or the src/lib it uses:
 *   npm run build:mcp
 * (tests/mcp.test.ts fails if api/mcp.js is out of date.)
 */
import { build } from 'esbuild'

export const options = {
  entryPoints: ['server/mcp/handler.ts'],
  bundle: true, platform: 'node', format: 'esm', target: 'node20', jsx: 'automatic',
  define: { 'process.env.NODE_ENV': '"production"' },
  legalComments: 'none', logLevel: 'warning',
  banner: { js: "// GENERATED by `npm run build:mcp` from server/mcp/ — edit those files, not this one.\nimport { createRequire as __mastorRequire } from 'node:module'; const require = __mastorRequire(import.meta.url);" },
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  await build({ ...options, outfile: 'api/mcp.js' })
  console.log('api/mcp.js written')
}
