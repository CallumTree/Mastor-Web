/**
 * Bundles the Claude connector (server/mcp/) into api/mcp.js, and Ask, the in-app assistant built on the
 * same tools (server/agent/), into api/agent.js — each one self-contained file Vercel can run, carrying the
 * app's own calculations from src/lib. Run after changing server/ or the src/lib it uses:
 *   npm run build:mcp
 * (tests/mcp.test.ts and tests/agent.test.ts fail if either file is out of date.)
 */
import { build } from 'esbuild'

export const options = {
  entryPoints: ['server/mcp/handler.ts'],
  bundle: true, platform: 'node', format: 'esm', target: 'node20', jsx: 'automatic',
  define: { 'process.env.NODE_ENV': '"production"' },
  legalComments: 'none', logLevel: 'warning',
  // document readers load on demand from node_modules (Vercel ships them with the function)
  external: ['pdfjs-dist', 'mammoth', 'xlsx'],
  banner: { js: "// GENERATED by `npm run build:mcp` from server/ — edit those files, not this one.\nimport { createRequire as __mastorRequire } from 'node:module'; const require = __mastorRequire(import.meta.url);" },
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  await build({ ...options, outfile: 'api/mcp.js' })
  await build({ ...options, entryPoints: ['server/agent/handler.ts'], outfile: 'api/agent.js' })
  console.log('api/mcp.js and api/agent.js written')
}
